"""Persistent project catalog; one canonical resource register across projects."""
import json
from threading import RLock
from uuid import uuid4
from platform_app.config import DATA_DIR, SAMPLE_DATA_DIR

LOCK = RLock()
FILE = DATA_DIR / 'projects.json'
DEFAULTS = [
    {'id': 'airport-t1', 'name': '杭州萧山机场 · 航站楼作业项目', 'kind': 'airport',
     'location': '杭州萧山国际机场', 'center': [30.2361, 120.4344], 'runtime': 'airport',
     'description': '七区联合巡检 / 空中复核 / 物资交接', 'scene_note': '区域底图定位；作业模型使用 Open-RMF 航站楼，未做测绘配准'},
    {'id': 'dispatch-pool', 'name': '110kV 变电站巡检项目', 'kind': 'grid',
     'location': '杭州', 'runtime': 'grid', 'description': '站区巡检 / 设备复核 / 人员协作'},
]

def _load():
    if not FILE.exists():
        return {'active': 'airport-t1', 'projects': DEFAULTS}
    return json.loads(FILE.read_text(encoding='utf-8'))

def _save(data):
    FILE.parent.mkdir(parents=True, exist_ok=True)
    temp = FILE.with_suffix('.tmp')
    temp.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf-8')
    temp.replace(FILE)

def catalog():
    with LOCK:
        return _load()

def active_project():
    data = catalog()
    return next(p for p in data['projects'] if p['id'] == data['active'])

def update_project(payload):
    # Always acquire airport before project locks, also used by task creation.
    from platform_app.services.airport_service import LOCK as AIRPORT_LOCK, runtime_status
    with AIRPORT_LOCK, LOCK:
        data = _load()
        if 'active' in payload:
            if not any(p['id'] == payload['active'] for p in data['projects']):
                raise ValueError('项目不存在')
            # Prevent assigning the same physical fleet to two projects mid-task.
            if payload['active'] != data['active'] and runtime_status().get('mission', {}).get('status') == 'running':
                raise ValueError('机场任务正在执行，请待设备归位后切换作业项目')
            data['active'] = payload['active']
        else:
            name = str(payload.get('name', '')).strip()
            kind = payload.get('kind')
            if not name or kind not in ('airport', 'grid'):
                raise ValueError('请填写项目名称并选择场景类型')
            data['projects'].append({'id': 'project-' + uuid4().hex[:10], 'name': name[:80],
                'kind': kind, 'location': str(payload.get('location', ''))[:120],
                'runtime': None, 'description': '待配置地图与运行服务'})
        _save(data)
        return data

def registry():
    """IDs and names are read from the platform master, never generated by a UI."""
    records = json.loads((SAMPLE_DATA_DIR / 'resources.json').read_text(encoding='utf-8'))
    file = DATA_DIR / 'resource-profiles.json'
    overrides = json.loads(file.read_text(encoding='utf-8')) if file.exists() else {}
    return [dict(r, **overrides.get(r['id'], {})) for r in records]

def update_resource(payload):
    rid = payload.get('id')
    if not any(r['id'] == rid for r in registry()):
        raise ValueError('当前编组固定为 28 个资源，请编辑已有编号；扩容需要配置运行驱动')
    name = str(payload.get('name', '')).strip()
    if not name: raise ValueError('设备名称不能为空')
    with LOCK:
        file = DATA_DIR / 'resource-profiles.json'
        rows = json.loads(file.read_text(encoding='utf-8')) if file.exists() else {}
        rows[rid] = {k:str(payload[k])[:100] for k in ('name','vendor','protocol','access') if k in payload}
        file.parent.mkdir(parents=True, exist_ok=True)
        temp = file.with_suffix('.tmp')
        temp.write_text(json.dumps(rows, ensure_ascii=False), encoding='utf-8'); temp.replace(file)
    return {'success': True}
